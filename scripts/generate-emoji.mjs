/**
 * Generates app/components/global/emoji/data.ts: the emoji BEmojiPicker offers, by group, from
 * emojibase-data's English dataset. Only what the picker shows goes in: the glyph, its name and
 * its search keywords. Skin-tone variants and the "component" group (bare skin tones and hair
 * styles) are left out, and so is anything newer than MAX_VERSION, which many phones and
 * desktops still draw as an empty box.
 *
 * Run `node scripts/generate-emoji.mjs` after bumping emojibase-data.
 */
import { createRequire } from "node:module";
import { writeFileSync, mkdirSync } from "node:fs";

const require = createRequire(import.meta.url);
const emojis = require("emojibase-data/en/data.json");
const { groups } = require("emojibase-data/en/messages.json");

const MAX_VERSION = 15;
const SKIP_GROUPS = new Set(["component"]);
const OUT = new URL("../app/components/global/emoji/", import.meta.url);

const keys = new Map(groups.map((group) => [group.order, group.key]));
const byGroup = new Map(
  groups.filter((group) => !SKIP_GROUPS.has(group.key)).map((group) => [group.key, []]),
);

for (const emoji of [...emojis].sort((a, b) => a.order - b.order)) {
  const list = byGroup.get(keys.get(emoji.group));
  if (!list || emoji.version > MAX_VERSION) continue;
  const words = new Set(emoji.label.toLowerCase().split(/\s+/));
  const keywords = (emoji.tags ?? []).filter((tag) => !words.has(tag.toLowerCase()));
  list.push([emoji.emoji, emoji.label, keywords.join(" ")]);
}

const body = [...byGroup]
  .map(([key, list]) => `  ${JSON.stringify(key)}: [\n${list.map((e) => `    ${JSON.stringify(e)},`).join("\n")}\n  ],`)
  .join("\n");

mkdirSync(OUT, { recursive: true });
writeFileSync(
  new URL("data.ts", OUT),
  `// Generated by scripts/generate-emoji.mjs from emojibase-data; do not edit.\n` +
    `import type { EmojiGroups } from "./types";\n\n` +
    `export default {\n${body}\n} satisfies EmojiGroups;\n`,
);
const total = [...byGroup.values()].reduce((sum, list) => sum + list.length, 0);
console.log(`${total} emoji in ${byGroup.size} groups`);
